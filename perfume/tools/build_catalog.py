"""Build catalog.js from the "Perfume Picture Menu" sheet.

Usage:
  1. In Google Sheets: File > Download > CSV (Sheet1).
  2. python3 tools/build_catalog.py path/to/menu.csv

Reads Brand, Fragrance, Concentration, Gender, Category, Rarity and price.
The "Site" image column is ignored on purpose: those links point to other
websites' photos. Add your own photos in img/bottles/ instead (see img/README.md).
"""
import csv, json, re, sys, unicodedata
from pathlib import Path

GENDER = {"men": "Men", "man": "Men", "male": "Men",
          "women": "Women", "woman": "Women", "female": "Women",
          "unisex": "Unisex"}
CATEGORY = {"designer": "designer", "niche": "niche", "middle eastern": "arabian",
            "celebrity": "celebrity", "unisex": "niche"}

def slug(s):
    s = unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode()
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")

def main(src):
    rows = list(csv.reader(open(src, encoding="utf-8")))
    head = [h.strip().lower() for h in rows[0]]
    col = lambda name: head.index(name)
    price_col = col("rarity") + 1  # unlabeled column right after Rarity
    out, seen = [], set()
    for r in rows[1:]:
        r = r + [""] * (len(head) - len(r))
        brand, name = r[col("brand")].strip(), " ".join(r[col("fragrance")].split())
        if not brand or not name:
            continue
        conc = r[col("concentration")].strip()
        pid = slug(f"{brand} {name} {conc}")
        n = 2
        while pid in seen:
            pid = slug(f"{brand} {name} {conc} {n}"); n += 1
        seen.add(pid)
        price = re.sub(r"[^\d]", "", r[price_col])
        rarity = r[col("rarity")].strip().upper()
        out.append({
            "id": pid,
            "brand": brand.title() if brand.isupper() and len(brand) > 4 else brand,
            "name": name,
            "type": conc,
            "gender": GENDER.get(r[col("gender")].strip().lower(), "Unisex"),
            "category": CATEGORY.get(r[col("category")].strip().lower(), "designer"),
            "rare": "RARE" in rarity,
            "fast": "FAST" in rarity,
            "price": int(price) if price else None,
        })
    dest = Path(__file__).resolve().parent.parent / "catalog.js"
    dest.write_text("// Generated by tools/build_catalog.py from the perfume menu sheet. Do not edit by hand.\n"
                    "window.CATALOG = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n",
                    encoding="utf-8")
    print(f"{len(out)} perfumes -> {dest}")

if __name__ == "__main__":
    main(sys.argv[1])
